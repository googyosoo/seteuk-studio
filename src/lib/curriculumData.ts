/**
 * 교과군 판별 헬퍼
 */
export function getSubjectGroup(subject: string): string {
  if (subject.includes('영어')) return '영어과';
  if (subject.includes('국어') || subject.includes('문학') || subject.includes('독서')) return '국어과';
  if (subject.includes('사회') || subject.includes('한국사') || subject.includes('역사') || subject.includes('경제') || subject.includes('지리')) return '사회/역사과';
  if (subject.includes('과학') || subject.includes('물리') || subject.includes('화학') || subject.includes('생명') || subject.includes('지구')) return '과학과';
  if (subject.includes('수학') || subject.includes('대수') || subject.includes('미적분') || subject.includes('확률')) return '수학과';
  return '기타교과';
}
